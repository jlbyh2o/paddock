/** A deterministic wobble, so sparklines look alive without a random seed. */
function series(n: number, base: number, swing: number, phase = 0): number[] {
  const out: number[] = [];
  for (let i = 0; i < n; i += 1) {
    const t = (i + phase) / 7;
    const v = base + Math.sin(t) * swing + Math.sin(t / 3.1) * (swing / 2);
    out.push(Math.max(0, Math.round(v)));
  }
  return out;
}

